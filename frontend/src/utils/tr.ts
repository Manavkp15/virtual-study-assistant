// Gujarati to Devanagari script converter for untranslated Gujarati text (chapters, topics, questions, etc.)
export function guToDevanagari(str: string): string {
  if (!str) return str;
  return str.replace(/[\u0A80-\u0AFF]/g, (ch) => {
    const code = ch.charCodeAt(0);
    // Convert 1:1 to Devanagari
    return String.fromCharCode(code - 0x0180);
  });
}

